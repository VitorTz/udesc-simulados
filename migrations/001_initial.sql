-- UDESC Simulados: first PostgreSQL schema.
-- Keep migrations immutable once applied. Apply with: python -m scripts.migrate
CREATE TABLE IF NOT EXISTS editions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label TEXT NOT NULL UNIQUE,
    imported_at TEXT NOT NULL,
    warning TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL REFERENCES editions(id) ON DELETE CASCADE,
    role TEXT NOT NULL CHECK (role IN ('morning','afternoon','key')),
    path TEXT NOT NULL, -- private R2 object key, NEVER a public URL or local path
    filename TEXT NOT NULL,
    UNIQUE(edition_id,role)
);

CREATE TABLE IF NOT EXISTS questions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edition_id BIGINT NOT NULL REFERENCES editions(id) ON DELETE CASCADE,
    document_id BIGINT NOT NULL REFERENCES documents(id) ON DELETE CASCADE,
    session TEXT NOT NULL CHECK(session IN ('morning','afternoon')),
    number INTEGER NOT NULL CHECK(number BETWEEN 1 AND 50),
    subject TEXT NOT NULL,
    text_content TEXT NOT NULL DEFAULT '',
    clips_json TEXT NOT NULL DEFAULT '[]',
    source_page INTEGER NOT NULL DEFAULT 0 CHECK(source_page >= 0),
    correct_answer TEXT CHECK(correct_answer IN ('A','B','C','D','E') OR correct_answer IS NULL),
    annulled SMALLINT NOT NULL DEFAULT 0 CHECK(annulled IN (0,1)),
    difficulty INTEGER CHECK(difficulty IS NULL OR difficulty BETWEEN 1 AND 5),
    UNIQUE(edition_id,session,number)
);

CREATE TABLE IF NOT EXISTS notes (
    question_id BIGINT PRIMARY KEY REFERENCES questions(id) ON DELETE CASCADE,
    body TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    config_json TEXT NOT NULL,
    created_at TEXT NOT NULL,
    completed_at TEXT,
    status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','completed'))
);

CREATE TABLE IF NOT EXISTS attempt_items (
    attempt_id BIGINT NOT NULL REFERENCES attempts(id) ON DELETE CASCADE,
    question_id BIGINT REFERENCES questions(id) ON DELETE SET NULL,
    position INTEGER NOT NULL,
    selected_answer TEXT CHECK(selected_answer IN ('A','B','C','D','E') OR selected_answer IS NULL),
    flagged SMALLINT NOT NULL DEFAULT 0 CHECK(flagged IN (0,1)),
    snapshot_subject TEXT NOT NULL,
    snapshot_edition TEXT NOT NULL,
    snapshot_correct TEXT,
    snapshot_annulled SMALLINT NOT NULL DEFAULT 0 CHECK(snapshot_annulled IN (0,1)),
    PRIMARY KEY(attempt_id,position)
);

CREATE INDEX IF NOT EXISTS idx_questions_subject ON questions(subject);
CREATE INDEX IF NOT EXISTS idx_questions_edition ON questions(edition_id);
CREATE INDEX IF NOT EXISTS idx_attempt_items_attempt ON attempt_items(attempt_id);
CREATE INDEX IF NOT EXISTS idx_documents_edition ON documents(edition_id);
