-- Multi-tenant accounts and persistent sessions.
-- IMPORTANT: Existing editions/attempts are intentionally left without an owner.
-- They are inaccessible until explicitly assigned through scripts/claim_legacy_data.py.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_lowercase CHECK (email = lower(email))
);

CREATE TABLE user_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf_token CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT sessions_expiry_valid CHECK (expires_at > created_at)
);
CREATE INDEX idx_user_sessions_user_id ON user_sessions(user_id);
CREATE INDEX idx_user_sessions_expiry ON user_sessions(expires_at);

ALTER TABLE editions ADD COLUMN user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;
ALTER TABLE attempts ADD COLUMN user_id BIGINT REFERENCES users(id) ON DELETE CASCADE;

-- Legacy label uniqueness must be replaced: each account can have a 2025/1 edition.
ALTER TABLE editions DROP CONSTRAINT IF EXISTS editions_label_key;
CREATE UNIQUE INDEX uq_editions_user_label ON editions (user_id, label);
CREATE INDEX idx_editions_user_id ON editions(user_id);
CREATE INDEX idx_attempts_user_id ON attempts(user_id);
-- Child rows belong to their parent edition/attempt; API access checks always scope ownership.
