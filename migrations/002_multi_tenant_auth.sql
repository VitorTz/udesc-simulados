BEGIN;

-- ============================================================================
-- 1. USERS
-- ============================================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT users_email_unique UNIQUE (email),
    CONSTRAINT users_email_lowercase CHECK (email = lower(email))
);


-- ============================================================================
-- 2. USER SESSIONS
-- ============================================================================

CREATE TABLE IF NOT EXISTS user_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    csrf_token CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,

    CONSTRAINT sessions_expiry_valid CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_user_sessions_user_id
    ON user_sessions(user_id);

CREATE INDEX IF NOT EXISTS idx_user_sessions_expiry
    ON user_sessions(expires_at);


-- ============================================================================
-- 3. MULTI-TENANT COLUMNS
-- ============================================================================

ALTER TABLE editions
    ADD COLUMN IF NOT EXISTS user_id BIGINT;

ALTER TABLE attempts
    ADD COLUMN IF NOT EXISTS user_id BIGINT;


-- ============================================================================
-- 4. FOREIGN KEY CONSTRAINTS
-- ============================================================================

DO $$
BEGIN
    -- Editions foreign key
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'editions_user_id_fkey'
          AND conrelid = 'editions'::regclass
    ) THEN
        ALTER TABLE editions
            ADD CONSTRAINT editions_user_id_fkey
            FOREIGN KEY (user_id)
            REFERENCES users(id)
            ON DELETE CASCADE;
    END IF;

    -- Attempts foreign key
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'attempts_user_id_fkey'
          AND conrelid = 'attempts'::regclass
    ) THEN
        ALTER TABLE attempts
            ADD CONSTRAINT attempts_user_id_fkey
            FOREIGN KEY (user_id)
            REFERENCES users(id)
            ON DELETE CASCADE;
    END IF;
END
$$;


-- ============================================================================
-- 5. REMOVE LEGACY UNIQUENESS
-- ============================================================================

ALTER TABLE editions
    DROP CONSTRAINT IF EXISTS editions_label_key;


-- ============================================================================
-- 6. MULTI-TENANT UNIQUE INDEXES
-- ============================================================================

CREATE UNIQUE INDEX IF NOT EXISTS uq_editions_user_label
    ON editions(user_id, label);


-- ============================================================================
-- 7. MULTI-TENANT PERFORMANCE INDEXES
-- ============================================================================

CREATE INDEX IF NOT EXISTS idx_editions_user_id
    ON editions(user_id);

CREATE INDEX IF NOT EXISTS idx_attempts_user_id
    ON attempts(user_id);


COMMIT;